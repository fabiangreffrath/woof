void P_LoadNodes_DeePBSPV4(map_t *map)
{
    numnodes = (W_LumpLength(map->nodes) - 8) / sizeof(mapnode_deepbspv4_t);
    nodes = Z_Malloc(numnodes * sizeof(node_t), PU_LEVEL, 0);
    byte *data = W_CacheLumpNum(map->nodes, PU_STATIC);

    // [FG] skip header
    mapnode_deepbspv4_t *m = (mapnode_deepbspv4_t *)(data + 8);

    for (size_t i = 0; i < numnodes; i++)
    {
        node_t *no = &nodes[i];
        mapnode_deepbspv4_t *mn = &m[i];

        no->x = IntToFixed(SHORT(mn->x));
        no->y = IntToFixed(SHORT(mn->y));
        no->dx = IntToFixed(SHORT(mn->dx));
        no->dy = IntToFixed(SHORT(mn->dy));

        for (size_t j = 0; j < 2; j++)
        {
            // [MB] 2020-04-22: Fix endianess for DeePBSPV4 nodes
            no->children[j] = ULONG(mn->children[j]);

            for (size_t k = 0; k < 4; k++)
            {
                no->bbox[j][k] = IntToFixed(SHORT(mn->bbox[j][k]));
            }
        }
    }

    Z_Free(data);
}

// [FG] support maps with ZDBSP nodes

static void CheckOverflowZDBSP(int32_t *size, int32_t count)
{
    (*size) -= count;

    if ((*size) < 0)
    {
        I_Error("incorrectly built ZDBSP nodes");
    }
}

static void *DecompressZDBSP(map_t *map, byte **data, int32_t *length)
{
    // first estimate for compression rate:
    // output buffer size == 2.5 * input size
    int32_t outlen = 2.5 * (*length);
    byte *output = malloc(outlen);

    // initialize stream state for decompression
    z_stream zstream;
    memset(&zstream, 0, sizeof(zstream));
    zstream.next_in = *data;
    zstream.avail_in = *length;
    zstream.next_out = output;
    zstream.avail_out = outlen;

    if (inflateInit(&zstream) != Z_OK)
    {
        I_Error("Error during ZNOD nodes decompression initialization!");
    }

    // resize if output buffer runs full
    int err;
    while ((err = inflate(&zstream, Z_SYNC_FLUSH)) == Z_OK)
    {
        const int next_out_old = (int)(zstream.next_out - output);

        outlen *= 2;
        output = I_Realloc(output, outlen);
        zstream.next_out = output + next_out_old;
        zstream.avail_out = outlen - next_out_old;
    }

    if (err != Z_STREAM_END)
    {
        I_Error("Error during ZNOD nodes decompression!");
    }

    I_Printf(VB_DEBUG, "%s: ZNOD nodes compression ratio %.3f", __func__,
             (float)zstream.total_out / zstream.total_in);

    *data = output;
    *length = zstream.total_out;

    if (inflateEnd(&zstream) != Z_OK)
    {
        I_Error("Error during ZNOD nodes decompression shut-down!");
    }

    // release the original data lump
    W_CacheLumpNum(map->znodes, PU_CACHE);

    return output;
}

static void LoadSegs_XNOD(map_t *map, byte *data)
{
    for (size_t i = 0; i < numsegs; i++)
    {
        line_t *ldef;
        uint32_t linedef;
        uint8_t side;
        seg_t *li = &segs[i];
        mapseg_xnod_t *ml = (mapseg_xnod_t *)data + i;
        uint32_t v1, v2;

        v1 = LONG(ml->v1);
        v2 = LONG(ml->v2);
        li->v1 = &vertexes[v1];
        li->v2 = &vertexes[v2];

        linedef = USHORT(ml->linedef);
        // Andrey Budko: check for wrong indexes
        if (linedef >= numlines)
        {
            I_Error("seg %zu references a non-existent linedef %d", i, linedef);
        }

        ldef = &lines[linedef];
        li->linedef = ldef;
        side = ml->side;

        // Andrey Budko: fix wrong side index
        if (side != 0 && side != 1)
        {
            side = 1;
        }

        // Andrey Budko: check for wrong indexes
        if (ldef->sidenum[side] >= numsides)
        {
            I_Error(
                "linedef %d for seg %zu references a non-existent sidedef %d",
                linedef, i, ldef->sidenum[side]);
        }

        li->sidedef = &sides[ldef->sidenum[side]];

        /* cph 2006/09/30 - our frontsector can be the second side of the
         * linedef, so must check for NO_INDEX in case we are incorrectly
         * referencing the back of a 1S line */
        if (ldef->sidenum[side] != NO_INDEX)
        {
            li->frontsector = sides[ldef->sidenum[side]].sector;
        }
        else
        {
            li->frontsector = 0;
            I_Printf(VB_DEBUG, "%s: front of seg %zu has no sidedef\n",
                     __func__, i);
        }

        // seg angle and offset are not included
        li->angle = R_PointToAngle2(li->v1->x, li->v1->y, li->v2->x, li->v2->y);
        li->offset = P_GetOffset(li->v1, (ml->side ? ldef->v2 : ldef->v1));

        if (ldef->flags & ML_TWOSIDED && ldef->sidenum[side ^ 1] != NO_INDEX)
        {
            li->backsector = sides[ldef->sidenum[side ^ 1]].sector;
        }
        else
        {
            li->backsector = 0;
        }
    }
}

static void LoadSegs_XGL(map_t *map, byte *data)
{
    const mapseg_xgln_t *mln = (const mapseg_xgln_t *)data;
    const mapseg_xgl2_t *ml2 = (const mapseg_xgl2_t *)data;

    for (size_t i = 0; i < numsubsectors; ++i)
    {
        for (size_t j = 0; j < subsectors[i].numlines; ++j)
        {
            unsigned int v1;
            // unsigned int partner;
            unsigned int line;
            uint8_t side;
            seg_t *seg;

            if (map->bsp_format == BSP_XGLN || map->bsp_format == BSP_ZGLN)
            {
                v1 = LONG(mln->vertex);
                // partner = LONG(mln->partner);
                line = USHORT(mln->linedef);
                side = mln->side;
                FIX_NO_INDEX(line);
                mln++;
            }
            else
            {
                v1 = LONG(ml2->vertex);
                // partner = LONG(ml2->partner);
                line = ULONG(ml2->linedef);
                side = ml2->side;
                ml2++;
            }

            seg = &segs[subsectors[i].firstline + j];

            seg->v1 = &vertexes[v1];
            if (j == 0)
            {
                seg[subsectors[i].numlines - 1].v2 = seg->v1;
            }
            else
            {
                seg[-1].v2 = seg->v1;
            }

            if (line != NO_INDEX)
            {
                line_t *ldef;

                if (line >= numlines)
                {
                    I_Error("seg %zu, %zu references a non-existent linedef %d",
                            i, j, line);
                }

                ldef = &lines[line];
                seg->linedef = ldef;

                if (side != 0 && side != 1)
                {
                    I_Error("seg %zu, %zu references a non-existent side %d", i,
                            j, side);
                }

                if (ldef->sidenum[side] >= numsides)
                {
                    I_Error("linedef %d for seg %zu, %zu "
                            "references a non-existent sidedef %d",
                            line, i, j, ldef->sidenum[side]);
                }

                seg->sidedef = &sides[ldef->sidenum[side]];

                /* cph 2006/09/30 - our frontsector can be the second side of
                 * the linedef, so must check for NO_INDEX in case we are
                 * incorrectly referencing the back of a 1S line */
                if (ldef->sidenum[side] != NO_INDEX)
                {
                    seg->frontsector = sides[ldef->sidenum[side]].sector;
                }
                else
                {
                    seg->frontsector = 0;
                    I_Printf(VB_WARNING,
                             "%s: front of seg %zu, %zu has no sidedef",
                             __func__, i, j);
                }

                if (ldef->flags & ML_TWOSIDED
                    && (ldef->sidenum[side ^ 1] != NO_INDEX))
                {
                    seg->backsector = sides[ldef->sidenum[side ^ 1]].sector;
                }
                else
                {
                    seg->backsector = 0;
                }

                seg->offset =
                    P_GetOffset(seg->v1, (side ? ldef->v2 : ldef->v1));
            }
            else
            {
                seg->angle = 0;
                seg->offset = 0;
                seg->linedef = NULL;
                seg->sidedef = NULL;
                seg->frontsector = segs[subsectors[i].firstline].frontsector;
                seg->backsector = seg->frontsector;
            }
        }

        // Need all vertices to be defined before setting angles
        for (size_t j = 0; j < subsectors[i].numlines; ++j)
        {
            seg_t *seg = &segs[subsectors[i].firstline + j];

            if (seg->linedef)
            {
                seg->angle = R_PointToAngle2(seg->v1->x, seg->v1->y, seg->v2->x,
                                             seg->v2->y);
            }
        }
    }
}

void P_LoadBSPTree_ZDBSP(map_t *map)
{
    byte *data;
    byte *output = NULL;

    uint32_t orgVerts, newVerts;
    uint32_t numSubs, currSeg;
    uint32_t numSegs;
    uint32_t numNodes;
    vertex_t *newvertarray = NULL;

    uint32_t value;

    int32_t len = W_LumpLength(map->znodes);
    data = W_CacheLumpNum(map->znodes, PU_LEVEL);

    // char[4]
    CheckOverflowZDBSP(&len, 4);
    data += 4;

    bsp_format_t format = map->bsp_format;

    boolean compressed = format == BSP_ZNOD || format == BSP_ZGLN
                         || format == BSP_ZGL2 || format == BSP_ZGL3;

    int32_t version = (format == BSP_XGL3 || format == BSP_ZGL3)   ? 3
                      : (format == BSP_XGL2 || format == BSP_ZGL2) ? 2
                      : (format == BSP_XGLN || format == BSP_ZGLN) ? 1
                                                                   : 0;

    // 0. Uncompress nodes lump (or simply skip header)
    if (compressed)
    {
        output = DecompressZDBSP(map, &data, &len);
    }

    // 1. Load new vertices added during node building

    CheckOverflowZDBSP(&len, sizeof(orgVerts));
    memcpy(&value, data, sizeof(orgVerts));
    orgVerts = LONG(value);
    data += sizeof(orgVerts);

    CheckOverflowZDBSP(&len, sizeof(newVerts));
    memcpy(&value, data, sizeof(newVerts));
    newVerts = LONG(value);
    data += sizeof(newVerts);

    if (orgVerts + newVerts == numvertexes)
    {
        newvertarray = vertexes;
    }
    else
    {
        newvertarray =
            arena_alloc_num(world_arena, vertex_t, orgVerts + newVerts);
        memcpy(newvertarray, vertexes, orgVerts * sizeof(vertex_t));
        memset(newvertarray + orgVerts, 0, newVerts * sizeof(vertex_t));
    }

    CheckOverflowZDBSP(&len, newVerts * (sizeof(newvertarray[0].x) + sizeof(newvertarray[0].y)));
    for (size_t i = 0; i < newVerts; i++)
    {
        memcpy(&value, data, sizeof(newvertarray[0].x));
        newvertarray[i + orgVerts].r_x = newvertarray[i + orgVerts].x =
            LONG(value);
        data += sizeof(newvertarray[0].x);

        memcpy(&value, data, sizeof(newvertarray[0].y));
        newvertarray[i + orgVerts].r_y = newvertarray[i + orgVerts].y =
            LONG(value);
        data += sizeof(newvertarray[0].y);
    }

    if (vertexes != newvertarray)
    {
        for (size_t i = 0; i < numlines; i++)
        {
            line_t *line = &lines[i];
            line->v1 = line->v1 - vertexes + newvertarray;
            line->v2 = line->v2 - vertexes + newvertarray;
        }

        vertexes = newvertarray;
        numvertexes = orgVerts + newVerts;
    }

    // 2. Load subsectors

    CheckOverflowZDBSP(&len, sizeof(numSubs));
    memcpy(&value, data, sizeof(numSubs));
    numSubs = LONG(value);
    data += sizeof(numSubs);

    if (numSubs < 1)
    {
        I_Error("No subsectors in map!");
    }

    numsubsectors = numSubs;
    subsectors = arena_alloc_num(world_arena, subsector_t, numsubsectors);

    CheckOverflowZDBSP(&len, numSubs * sizeof(mapsubsector_xnod_t));
    for (size_t i = currSeg = 0; i < numsubsectors; i++)
    {
        subsector_t *sss = &subsectors[i];
        mapsubsector_xnod_t *mseg = (mapsubsector_xnod_t *)data + i;

        sss->firstline = currSeg;
        sss->numlines = ULONG(mseg->numsegs);
        currSeg += ULONG(mseg->numsegs);
    }

    data += numsubsectors * sizeof(mapsubsector_xnod_t);

    // 3. Load segs
    CheckOverflowZDBSP(&len, sizeof(numSegs));
    memcpy(&value, data, sizeof(numSegs));
    numSegs = ULONG(value);
    data += sizeof(numSegs);

    // The number of stored segs should match the number of segs used by
    // subsectors
    if (numSegs != currSeg)
    {
        I_Error("Incorrect number of segs in XNOD nodes!");
    }

    numsegs = numSegs;
    segs = arena_alloc_num(world_arena, seg_t, numsegs);

    switch (version)
    {
        case 0:
            CheckOverflowZDBSP(&len, numsegs * sizeof(mapseg_xnod_t));
            LoadSegs_XNOD(map, data);
            data += numsegs * sizeof(mapseg_xnod_t);
            break;
        case 1:
            CheckOverflowZDBSP(&len, numsegs * sizeof(mapseg_xgln_t));
            LoadSegs_XGL(map, data);
            data += numsegs * sizeof(mapseg_xgln_t);
            break;
        case 2:
        case 3:
            CheckOverflowZDBSP(&len, numsegs * sizeof(mapseg_xgl2_t));
            LoadSegs_XGL(map, data);
            data += numsegs * sizeof(mapseg_xgl2_t);
            break;
        default:
            I_Error("How did we get here?");
            break;
    }

    // 4. Load nodes
    CheckOverflowZDBSP(&len, sizeof(numNodes));
    memcpy(&value, data, sizeof(numNodes));
    numNodes = ULONG(value);
    data += sizeof(numNodes);

    numnodes = numNodes;
    nodes = Z_Malloc(numnodes * sizeof(node_t), PU_LEVEL, 0);

    size_t node_size =
        (version == 3) ? sizeof(mapnode_xgl3_t) : sizeof(mapnode_xnod_t);
    CheckOverflowZDBSP(&len, numNodes * node_size);

    for (size_t i = 0; i < numnodes; i++)
    {
        node_t *no = &nodes[i];

        if (version == 3)
        {
            const mapnode_xgl3_t *mn3 = (const mapnode_xgl3_t *)data + i;
            no->x = LONG(mn3->x);
            no->y = LONG(mn3->y);
            no->dx = LONG(mn3->dx);
            no->dy = LONG(mn3->dy);
            for (size_t j = 0; j < 2; j++)
            {
                no->children[j] = ULONG(mn3->children[j]);
                for (size_t k = 0; k < 4; k++)
                {
                    no->bbox[j][k] = IntToFixed(SHORT(mn3->bbox[j][k]));
                }
            }
        }
        else
        {
            const mapnode_xnod_t *mn = (const mapnode_xnod_t *)data + i;
            no->x = IntToFixed(SHORT(mn->x));
            no->y = IntToFixed(SHORT(mn->y));
            no->dx = IntToFixed(SHORT(mn->dx));
            no->dy = IntToFixed(SHORT(mn->dy));
            for (size_t j = 0; j < 2; j++)
            {
                no->children[j] = ULONG(mn->children[j]);
                for (size_t k = 0; k < 4; k++)
                {
                    no->bbox[j][k] = IntToFixed(SHORT(mn->bbox[j][k]));
                }
            }
        }
    }

    if (compressed && output)
    {
        free(output);
    }
    else
    {
        W_CacheLumpNum(map->znodes, PU_CACHE);
    }
}
